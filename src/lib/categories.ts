export function categoryLabel(slug: string): string {
  if (CATEGORY_PT[slug]) return CATEGORY_PT[slug];
  // fallback: transforma "home-and-decor" em "Home And Decor"
  return slug
    .split(/[-_]/)
    .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
    .join(" ");
}
